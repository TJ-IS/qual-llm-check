# -*- coding: utf-8 -*-
import io
f = '34_论文一_AgentShield-Adversary_编码智能体对抗攻击的系统化生成与威胁建模_v3.1.md'
t = io.open(f, encoding='utf-8').read()

# 1) 6.1 实验设置句声明消融
old1 = '进行系统比较。攻击成功率（ASR）为评估指标'
new1 = '进行系统比较，并开展训练设计的组件消融。攻击成功率（ASR）为评估指标'
assert t.count(old1) == 1
t = t.replace(old1, new1)

# 2) 插入预期发现四（消融分析）
old2 = '### 6.2 实验二（D_att 基准质量与攻击面刻画）'
new2 = ('预期发现四（消融分析）。本文方法相对基线的优势归因于三个训练设计组件。其一，行为克隆预训练为奖励稀疏情境提供攻击先验。其二，两级动作分解将通道选择显式纳入决策。其三，危害与隐蔽性的联合奖励设计。消融分析考察各组件的贡献。移除行为克隆预训练的变体在奖励稀疏情境下训练不稳定，攻击成功率显著下降【占位】。将动作空间退化为单级扁平空间的变体无法显式选择通道，攻击面覆盖显著下降【占位】。移除隐蔽性奖励的变体生成攻击的平均编辑成本显著上升，更易被公开检测基线识别【占位】。结果详见随论文发布的评估脚本。\n\n'
        + old2)
assert t.count(old2) == 1
t = t.replace(old2, new2)

# 3) 重编号 6.2 的三条预期发现
ren = [
 ('预期发现四（标注质量）', '预期发现五（标注质量）'),
 ('预期发现五（攻击面覆盖）', '预期发现六（攻击面覆盖）'),
 ('预期发现六（迁移性）', '预期发现七（迁移性）'),
]
for old, new in ren:
    assert t.count(old) == 1, old
    t = t.replace(old, new)

io.open(f, 'w', encoding='utf-8', newline='').write(t)
print('34 ch6 已修改')
