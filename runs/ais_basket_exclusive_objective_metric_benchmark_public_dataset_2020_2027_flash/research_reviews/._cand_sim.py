# -*- coding: utf-8 -*-
import difflib, re
def norm(s):
    s = re.sub(r"【[^】]*】", "P", s)
    s = re.sub(r"\s+", "", s)
    return s
def sim(a, b):
    return difflib.SequenceMatcher(None, norm(a), norm(b)).ratio()

print("== 1. 34 P1 S2 vs 36 P1 S2 ==")
a = "给定问题描述与仓库上下文，编码智能体能够自主规划并执行读取文件、编辑代码、运行测试、调用工具等动作，直至完成任务（Yang et al., 2024）。"
b = "编码智能体根据问题描述与仓库上下文推进任务，在任务执行中依次读取文件、编辑代码、运行测试并调用工具，直至任务完成。"
print("now:", round(sim(a,b),3))
b2 = "在任务执行中，编码智能体持续读取文件、编辑代码、运行测试并调用工具，其动作序列与仓库状态构成可观测的行为证据。"
print("b2 vs 34P1S2:", round(sim(a,b2),3))

