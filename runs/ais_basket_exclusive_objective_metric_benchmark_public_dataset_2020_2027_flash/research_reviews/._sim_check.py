import re, difflib

def norm(s):
    s = re.sub(r"【[^】]*】", "", s)
    s = re.sub(r"（[^）]*）", "", s)
    s = re.sub(r"\s+", "", s)
    return s

def sim(a, b):
    return difflib.SequenceMatcher(None, norm(a), norm(b)).ratio()

